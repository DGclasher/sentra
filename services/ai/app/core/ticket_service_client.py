import logging

import httpx
from app.core.config import settings

logger = logging.getLogger(__name__)


class TicketServiceClientError(Exception):
    """Raised when the Ticket Service cannot provide a valid response."""


class TicketServiceClient:
    """Asynchronous client for user-scoped Ticket Service read operations.

    The AI Service passes the authenticated user's ID to this client. The
    client forwards that identity to the Ticket Service, which remains the
    authority for ticket ownership and access checks. The user ID is never
    taken from tool arguments generated by the language model.

    Raises:
        TicketServiceClientError: If the Ticket Service cannot be reached,
            returns an HTTP error, or returns an invalid response.
    """

    DEFAULT_TIMEOUT = 10.0

    def __init__(self, client: httpx.AsyncClient | None = None):
        """Create a client using the configured internal Ticket Service URL."""
        self.base_url = settings.ticket_service_url.rstrip("/")
        self._client = client

    def set_client(self, client: httpx.AsyncClient) -> None:
        """Attach the application-scoped HTTP client."""
        self._client = client

    def clear_client(self) -> None:
        """Detach the application-scoped HTTP client after shutdown."""
        self._client = None

    def _get_client(self) -> httpx.AsyncClient:
        if self._client is None:
            raise TicketServiceClientError(
                "Ticket Service HTTP client is not initialized"
            )
        return self._client

    async def get_my_tickets(self, user_id: str) -> list[dict]:
        """Return all tickets owned by the authenticated user.

        Args:
            user_id: The authenticated end-user ID supplied by the AI Service
                dependency, not by the model or request body.

        Returns:
            The Ticket Service JSON list of user-owned ticket objects.

        Raises:
            TicketServiceClientError: If the request fails or the response is
                not a list.
        """
        url = f"{self.base_url}/api/v1/tickets/user"
        logger.info(
            "Requesting authenticated user's tickets from Ticket Service")
        try:
            response = await self._get_client().get(
                url,
                headers={"X-User-Id": user_id},
            )
            response.raise_for_status()
        except httpx.TimeoutException as error:
            logger.warning("Ticket Service tickets request timed out")
            raise TicketServiceClientError(
                "Ticket Service request timed out") from error
        except httpx.HTTPStatusError as error:
            logger.warning(
                "Ticket Service tickets request returned status %s",
                error.response.status_code,
            )
            raise TicketServiceClientError(
                "Ticket Service returned an HTTP error") from error
        except httpx.RequestError as error:
            logger.warning("Ticket Service tickets request failed: %s", error)
            raise TicketServiceClientError(
                "Ticket Service request failed") from error
        logger.info(
            "Ticket Service tickets request completed with status %s",
            response.status_code,
        )
        try:
            result = response.json()
        except ValueError as error:
            logger.warning(
                "Ticket Service tickets response was not valid JSON")
            raise TicketServiceClientError(
                "Ticket Service returned invalid JSON") from error
        if not isinstance(result, list):
            logger.warning(
                "Ticket Service tickets response had an invalid shape")
            raise TicketServiceClientError(
                "Ticket Service returned an invalid tickets response")
        return result

    async def get_my_ticket(self, user_id: str, ticket_id: str) -> dict:
        """Return one ticket only when it belongs to the authenticated user.

        Args:
            user_id: The authenticated end-user ID supplied by the AI Service
                dependency, not by the model or request body.
            ticket_id: The ticket identifier selected by the model from the
                declared tool argument.

        Returns:
            The Ticket Service JSON ticket object.

        Raises:
            TicketServiceClientError: If the request fails or the response is
                not an object.
        """
        url = f"{self.base_url}/api/v1/tickets/user/{ticket_id}"
        logger.info("Requesting ticket from Ticket Service")
        try:
            response = await self._get_client().get(
                url,
                headers={"X-User-Id": user_id},
            )
            response.raise_for_status()
        except httpx.TimeoutException as error:
            logger.warning("Ticket Service ticket request timed out")
            raise TicketServiceClientError(
                "Ticket Service request timed out") from error
        except httpx.HTTPStatusError as error:
            logger.warning(
                "Ticket Service ticket request returned status %s",
                error.response.status_code,
            )
            raise TicketServiceClientError(
                "Ticket Service returned an HTTP error") from error
        except httpx.RequestError as error:
            logger.warning("Ticket Service ticket request failed: %s", error)
            raise TicketServiceClientError(
                "Ticket Service request failed") from error
        logger.info(
            "Ticket Service ticket request completed with status %s",
            response.status_code,
        )
        try:
            result = response.json()
        except ValueError as error:
            logger.warning("Ticket Service ticket response was not valid JSON")
            raise TicketServiceClientError(
                "Ticket Service returned invalid JSON") from error
        if not isinstance(result, dict):
            logger.warning(
                "Ticket Service ticket response had an invalid shape")
            raise TicketServiceClientError(
                "Ticket Service returned an invalid ticket response")
        return result
